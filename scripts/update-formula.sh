#!/usr/bin/env bash
# update-formula.sh <tag> writes Formula/modelpick.rb for that modelpick
# release from the release's SHA256SUMS. The formula installs the release
# archives, which the release job has already checked; it never builds from
# source (a build from GitHub's source tarball has no version control
# information and prints `modelpick dev`).
#
# MODELPICK_RELEASE_BASE overrides where SHA256SUMS is fetched from (tests use
# a file:// fixture); the URLs written into the formula always point at the
# GitHub release.
set -euo pipefail

die() { echo "update-formula: $*" >&2; exit 1; }

[ $# -eq 1 ] || die "usage: update-formula.sh vX.Y.Z"
tag=$1
[[ $tag =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "tag $tag is not vX.Y.Z (prereleases are not published to the tap)"
version=${tag#v}

root=$(cd "$(dirname "$0")/.." && pwd)
release=https://github.com/meatlover/modelpick/releases/download/$tag
base=${MODELPICK_RELEASE_BASE:-$release}

sums=$(curl -fsSL "$base/SHA256SUMS") || die "cannot fetch $base/SHA256SUMS"

# sha <os>_<arch>: the checksum of that archive, or a failure naming it.
sha() {
  local file=modelpick_${version}_$1.tar.gz s
  s=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' <<<"$sums")
  [[ $s =~ ^[0-9a-f]{64}$ ]] || die "SHA256SUMS of $tag has no checksum for $file"
  echo "$s"
}

darwin_arm64=$(sha darwin_arm64)
darwin_amd64=$(sha darwin_amd64)
linux_arm64=$(sha linux_arm64)
linux_amd64=$(sha linux_amd64)

out=$root/Formula/modelpick.rb
tmp=$(mktemp "$out.XXXXXX")
trap 'rm -f "$tmp"' EXIT
cat >"$tmp" <<EOF
# Generated by scripts/update-formula.sh from the $tag release; do not edit.
class Modelpick < Formula
  desc "Picks an LLM subscription, account, model and thinking level from live usage"
  homepage "https://github.com/meatlover/modelpick"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$release/modelpick_${version}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$release/modelpick_${version}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$release/modelpick_${version}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$release/modelpick_${version}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "modelpick"
    pkgshare.install "config.example.json"
  end

  def caveats
    <<~EOS
      An example config is at
        #{pkgshare}/config.example.json
      Copy it to the path \`modelpick config\` names, edit it, then run
      \`modelpick doctor\`.
    EOS
  end

  test do
    assert_equal "modelpick v#{version}", shell_output("#{bin}/modelpick version").strip
  end
end
EOF
mv "$tmp" "$out"
trap - EXIT
echo "update-formula: Formula/modelpick.rb is $tag"
